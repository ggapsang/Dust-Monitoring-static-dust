--
-- 원래는 촬영 일시에 유효한 기준만 쓴다. 패드를 갈아 붙인 뒤에도 그 이전
-- 촬영분이 예전 기준으로 읽혀야 값이 이어지기 때문이다.
--
-- 다만 실증 중에는 기준을 나중에 등록하거나 부착 일시를 대충 넣는 일이
-- 잦아, 촬영보다 늦은 기준밖에 없어서 판독이 통째로 안 도는 경우가 생긴다.
-- 그때 쓰라고 실행 단위로 끄는 스위치를 둔다.
--
-- 실행마다 남긴다. 나중에 결과를 볼 때 이 값이 무엇이었는지 모르면, 어느
-- 기준과 견준 값인지 알 수 없다.
ALTER TABLE run ADD COLUMN IF NOT EXISTS ignore_baseline_window BOOLEAN NOT NULL DEFAULT false;
